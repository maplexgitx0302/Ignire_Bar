// Builds docs/scriptable/IgnireCalendar.js: the Scriptable widget with the
// calendar engine embedded, so users can paste a single self-contained file.
// Also builds docs/scriptable/source.js, which exposes the same text to the
// website's copy button without fetch() (fetch fails when opened via file://).
//
//   node scripts/build-scriptable.mjs           write the file
//   node scripts/build-scriptable.mjs --check   fail if the file is out of date

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const WEB_URL = "https://maplexgitx0302.github.io/Ignire_Bar/";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");
const outputPath = fileURLToPath(new URL("docs/scriptable/IgnireCalendar.js", root));
const sourcePath = fileURLToPath(new URL("docs/scriptable/source.js", root));

export function buildScriptable() {
  return read("scripts/scriptable-widget.js")
    .replace("/*@@IGNIRE_CORE@@*/", () => read("docs/ignire-calendar.js").trimEnd())
    .replace("@@WEB_URL@@", WEB_URL);
}

export function buildSourceModule(script = buildScriptable()) {
  return (
    "// Generated by scripts/build-scriptable.mjs: the Scriptable script as a string.\n" +
    `window.IgnireScriptableSource = ${JSON.stringify(script)};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const script = buildScriptable();
  const outputs = [
    [outputPath, script],
    [sourcePath, buildSourceModule(script)],
  ];
  for (const [path, content] of outputs) {
    if (!process.argv.includes("--check")) {
      writeFileSync(path, content);
    } else if (readFileSync(path, "utf8") !== content) {
      console.error(`${path} is out of date; run npm run build`);
      process.exit(1);
    }
  }
}
